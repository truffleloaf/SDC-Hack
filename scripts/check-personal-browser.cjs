const assert = require('node:assert/strict')
const { launchBrowser } = require('./browser-test-helpers.cjs')
const origin = process.env.PIVOTT_TEST_ORIGIN || 'http://localhost:3002'
const out = process.env.PIVOTT_SCREENSHOT_DIR || require('node:path').resolve(__dirname, '../docs')
;(async () => {
 const browser = await launchBrowser()
 const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light', reducedMotion: 'reduce' })
 const page = await context.newPage()
 page.setDefaultTimeout(15000)
 const errors = []
 page.on('pageerror', error => errors.push(error.message))
 const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('pivott:v1')))
 const visible = async (text) => page.getByText(text, { exact: false }).first().waitFor({ state: 'visible' })
 console.log('Homepage'); await page.goto(origin)
 await visible('No account needed to start.')
 await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: `${out}/pivott-desktop.png`, fullPage: true })
 await page.getByRole('link', { name: 'Map my work', exact: true }).first().click()
 await page.getByLabel('Your job title (optional)').fill('Accounts Executive')
 await page.getByRole('option', { name: /Finance Admin/ }).click()
 await visible('Choose your tasks · Step 2 of 3')
 assert.deepEqual((await state()).skills, {})
 console.log('Task editing'); const first = page.locator('details').first()
 await first.locator('summary').click()
 await first.getByLabel('Task name', { exact: true }).fill('Invoice checks with a deliberately long descriptive task name')
 await first.getByRole('spinbutton').fill('30')
 let saved = await state()
 assert(Math.abs(saved.selections.reduce((sum, item) => sum + item.share, 0) - 100) < 1e-7)
 await first.getByRole('button', { name: 'Remove task', exact: true }).click()
 assert.equal((await state()).selections.length, 5)
 await page.getByRole('button', { name: 'Undo', exact: true }).click()
 assert.equal((await state()).selections.length, 6)
 await page.locator('summary').filter({ hasText: 'Add your own task' }).click()
 const customForm = page.locator('details').filter({ has: page.locator('summary', { hasText: 'Add your own task' }) })
 await customForm.getByLabel('Task name', { exact: true }).fill('Team coordination for a custom workflow')
 await customForm.getByRole('button', { name: 'Add task', exact: true }).click()
 assert.equal((await state()).customTasks.length, 1)
 assert.equal((await state()).customTasks[0].baseExposure, undefined)
 await page.getByRole('link', { name: 'View my task map', exact: true }).filter({ visible: true }).first().click()
 await page.waitForURL('**/map'); console.log('Map')
 await visible('Not assessed yet')
 await visible('The percentage above describes assessed tasks only.')
 await page.getByRole('button', { name: 'Verify with API', exact: true }).click()
 await visible('Matches API:')
 const mapButtons = page.locator('svg [role="button"]')
 await mapButtons.first().focus()
 await page.keyboard.press('Enter')
 await visible('Human judgment:')
 await page.keyboard.press('Escape')
 await page.getByRole('radio', { name: 'List', exact: true }).click()
 await page.getByRole('button', { name: 'Show details', exact: true }).first().click()
 await visible('Human judgment:')
 assert(await page.getByText('Team coordination for a custom workflow').isVisible())
 await page.getByRole('link', { name: 'Rate skills for routes', exact: true }).click()
 console.log('Skills'); const select = page.getByRole('combobox').first()
 await select.selectOption('0')
 assert.equal(Object.values((await state()).skills)[0], 0)
 await select.selectOption('unknown')
 assert.equal(Object.keys((await state()).skills).length, 0)
 await page.getByRole('link', { name: 'Compare possible roles', exact: true }).filter({ visible: true }).first().click()
 console.log('Routes'); await visible('No skill match is shown until you rate relevant skills.')
 await page.getByRole('button', { name: 'Save for comparison', exact: true }).first().click()
 assert.equal((await state()).savedRouteIds.length, 1)
 await page.getByRole('button', { name: 'View route', exact: true }).first().click()
 await visible('provisional fit = 100 × task_similarity')
 await page.keyboard.press('Escape')
 await page.getByRole('button', { name: 'Build my plan', exact: true }).first().click()
 await visible('Partial plan:')
 await visible('Not estimated')
 assert.equal(await page.getByText('100%', { exact: true }).count(), 0)
 await page.goto(`${origin}/workspace`)
 await page.getByLabel('Career goal (optional)').fill('Explore operations roles')
 await page.getByLabel('Learning hours per week').fill('8')
 await page.goto(origin)
 await page.waitForURL('**/workspace')
 assert.equal((await state()).careerGoal, 'Explore operations roles')
 await page.reload()
 await visible('Your plan')
 await page.goto(`${origin}/signin?next=/pathway`)
 await visible('Account saving is not configured')
 assert.equal((await state()).jobTitle, 'Accounts Executive')
 await page.goto(`${origin}/map`)
 await page.getByRole('button', { name: 'Switch to dark mode' }).click()
 await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: `${out}/pivott-map-dark.png`, fullPage: true })
 await page.getByRole('button', { name: 'Switch to light mode' }).click()
 await page.setViewportSize({ width: 390, height: 844 })
 await page.locator('svg [role="button"]').first().click()
 await page.getByRole('heading', { name: 'Task details', exact: true }).waitFor()
 await page.getByRole('button', { name: 'Close details', exact: true }).click()
 await page.getByRole('heading', { name: 'Task details', exact: true }).waitFor({ state: 'hidden' })
 const overflow = await page.evaluate(() => ({ body: document.documentElement.scrollWidth, viewport: innerWidth }))
 assert(overflow.body <= overflow.viewport + 1, JSON.stringify(overflow))
 await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: `${out}/pivott-map-mobile.png`, fullPage: true })
 await page.goto(`${origin}/start`)
 const beforeRestore = await state()
 page.once('dialog', modal => modal.dismiss())
 await page.getByRole('button', { name: 'Restore defaults', exact: true }).click()
 assert.deepEqual((await state()).selections, beforeRestore.selections)
 page.once('dialog', modal => modal.accept())
 await page.getByRole('button', { name: 'Restore defaults', exact: true }).click()
 assert.equal((await state()).selections.length, 6)
 assert.equal((await state()).customTasks.length, 1)
 assert.deepEqual((await state()).skills, beforeRestore.skills)
 await page.getByRole('button', { name: 'More options', exact: true }).click()
 await page.getByRole('menuitem', { name: 'Reset demo', exact: true }).click()
 assert.equal((await state()).mode, 'demo')
 await page.getByRole('button', { name: 'More options', exact: true }).click()
 await page.getByRole('menuitem', { name: 'Exit demo profile', exact: true }).click()
 assert.equal((await state()).jobTitle, 'Accounts Executive')
 assert.equal((await state()).mode, 'personal')
 await page.goto(`${origin}/?welcome=1`)
 for (const scale of [1, 1.25, 2]) {
   await page.setViewportSize({ width: 320, height: 740 })
   await page.evaluate(scale => document.documentElement.style.fontSize = `${16 * scale}px`, scale)
   assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Homepage overflow at font scale ${scale}`)
 }
 await page.evaluate(() => document.documentElement.style.fontSize = '16px')
 await page.setViewportSize({ width: 390, height: 844 })
 await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: `${out}/pivott-mobile.png`, fullPage: true })
 assert.deepEqual(errors, [])
 console.log('PASS: desktop/mobile personal flow, task editing/rebalancing/Undo, custom unknowns, map/list details, API parity, unknown vs zero ratings, partial routes/plan, saved routes, return/refresh, guest sign-in fallback, dark/reduced-motion layouts, restore defaults, demo isolation, 320px homepage with 100/125/200% root font sizes; no page errors.')
 await browser.close()
})().catch(error => { console.error(error); process.exit(1) })
